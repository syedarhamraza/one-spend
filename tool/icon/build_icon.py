"""Builds every One Spend icon asset from the two Figma exports.

Inputs (tool/icon/figma/):
  logo-v2.png       1024 x 1024 composed icon (Figma "LOGO v2": glass stack on deep blue).
                    It is the full 108-unit adaptive canvas; launchers show the middle 72.
  monochrome.svg    1024 x 1024 one-colour silhouette (Figma "Monochrome (gaps)").

Outputs:
  android/app/src/main/res/
    mipmap-*/ic_launcher_foreground.webp   adaptive foreground (the composed icon, full bleed)
    drawable/ic_launcher_background.xml    adaptive background (deep blue, hidden behind it)
    drawable/ic_launcher_monochrome.xml    Android 13+ themed icon (vector)
    mipmap-*/ic_launcher(.._round).webp    icons for launchers without adaptive icons
    drawable(-v21)/splash_icon.png         splash screen icon
    drawable-anydpi/ic_stat_name.xml       notification icon (vector)
  assets/logos/app_logo.png                in-app logo (About, onboarding)
  tool/store_graphics/captures/logo.png    store icon and feature graphic source

Usage: python tool/icon/build_icon.py   (then run tool/store_graphics/render.ps1)
"""

import pathlib
import re

from PIL import Image, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parents[2]
FIGMA = ROOT / "tool/icon/figma"
RES = ROOT / "android/app/src/main/res"

DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
VISIBLE = 72 / 108          # share of the adaptive canvas a launcher shows
THEMED_SCALE = 0.698        # 450 px stack in LOGO v2 / 645 px mark in monochrome.svg
NOTIFICATION_SCALE = 1.35   # notification glyphs fill most of their 24 dp box

composite = Image.open(FIGMA / "logo-v2.png").convert("RGB")
assert composite.size == (1024, 1024), composite.size


def visible_square(size):
    """The part of the adaptive canvas a launcher shows, as an opaque square."""
    w = composite.width
    m = w * (1 - VISIBLE) / 2
    return composite.crop((round(m), round(m), round(w - m), round(w - m))).resize((size, size), Image.LANCZOS)


def masked(img, shape):
    """Applies a squircle-like rounded square or a circle mask (drawn 4x, then smoothed)."""
    size = img.width
    big = Image.new("L", (size * 4, size * 4), 0)
    draw = ImageDraw.Draw(big)
    if shape == "circle":
        draw.ellipse((0, 0, size * 4 - 1, size * 4 - 1), fill=255)
    else:
        draw.rounded_rectangle((0, 0, size * 4 - 1, size * 4 - 1), radius=round(size * 4 * 0.3), fill=255)
    out = img.convert("RGBA")
    out.putalpha(big.resize((size, size), Image.LANCZOS))
    return out


def svg_paths():
    """(d, evenodd) for each path in the monochrome SVG."""
    svg = (FIGMA / "monochrome.svg").read_text(encoding="utf-8")
    return [(m.group(2), "evenodd" in m.group(1) + m.group(3))
            for m in re.finditer(r'<path([^>]*?)\sd="([^"]+)"([^>]*)/>', svg)]


def vector_drawable(size_dp, scale, colour, comment):
    paths = "\n".join(
        f'        <path\n            android:fillColor="{colour}"\n'
        + ('            android:fillType="evenOdd"\n' if evenodd else "")
        + f'            android:pathData="{d}" />'
        for d, evenodd in svg_paths()
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tool/icon/build_icon.py from tool/icon/figma/monochrome.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp"
    android:height="{size_dp}dp"
    android:viewportWidth="1024"
    android:viewportHeight="1024">
    <group
        android:pivotX="512"
        android:pivotY="512"
        android:scaleX="{scale}"
        android:scaleY="{scale}">
{paths}
    </group>
</vector>
"""


BACKGROUND = """<?xml version="1.0" encoding="utf-8"?>
<!-- Adaptive icon background: the deep blue of the icon (the foreground covers it fully).
     Generated by tool/icon/build_icon.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:startX="54"
                android:startY="0"
                android:endX="54"
                android:endY="108"
                android:type="linear">
                <item android:offset="0" android:color="#FF2563EB" />
                <item android:offset="1" android:color="#FF0A1F66" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
"""


def main():
    written = []

    def save(img, rel, **kw):
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        img.save(path, **kw)
        written.append(rel)

    for name, k in DENSITIES.items():
        # Adaptive foreground: the whole composed icon (its glass refracts the blue it was drawn on).
        save(composite.resize((round(108 * k),) * 2, Image.LANCZOS),
             f"android/app/src/main/res/mipmap-{name}/ic_launcher_foreground.webp", quality=95, method=6)
        # Legacy icons (launchers without adaptive icons).
        tile = visible_square(round(48 * k))
        save(masked(tile, "square"), f"android/app/src/main/res/mipmap-{name}/ic_launcher.webp", lossless=True)
        save(masked(tile, "circle"), f"android/app/src/main/res/mipmap-{name}/ic_launcher_round.webp", lossless=True)
        # Old notification PNGs: the vector below takes priority on every supported Android version.
        old = RES / f"drawable-{name}/ic_stat_name.png"
        if old.exists():
            old.unlink()
            written.append(f"(removed) {old.relative_to(ROOT)}")

    (RES / "drawable/ic_launcher_background.xml").write_text(BACKGROUND, encoding="utf-8")
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(
        vector_drawable(108, THEMED_SCALE, "#FFFFFFFF", "Themed (Android 13+) icon: the stack silhouette."),
        encoding="utf-8")
    (RES / "drawable-anydpi/ic_stat_name.xml").write_text(
        vector_drawable(24, NOTIFICATION_SCALE, "#FFFFFFFF", "Notification icon: the stack silhouette."),
        encoding="utf-8")
    written += ["drawable/ic_launcher_background.xml", "drawable/ic_launcher_monochrome.xml",
                "drawable-anydpi/ic_stat_name.xml"]

    # Splash icon: the rounded tile inside the circle Android 12+ shows (2/3 of the canvas).
    splash = Image.new("RGBA", (288, 288), (0, 0, 0, 0))
    tile = masked(visible_square(132), "square")
    splash.paste(tile, ((288 - 132) // 2,) * 2, tile)
    save(splash, "android/app/src/main/res/drawable/splash_icon.png")
    save(splash, "android/app/src/main/res/drawable-v21/splash_icon.png")

    # In-app logo and the store graphics source: the visible square, full bleed.
    square = visible_square(1024)
    save(square, "assets/logos/app_logo.png", optimize=True)
    save(square, "tool/store_graphics/captures/logo.png", optimize=True)

    for w in written:
        print("  " + w)


if __name__ == "__main__":
    main()
